int	ft_sumdigits(int n)
{
	while (n > 9){
		int s = 0;
		while (n){
			s += n % 10;
			n /= 10;
		}
		n = s;
	}
	return (n);
}
#include <stdio.h>
int main(){
	printf("%d\n", ft_sumdigits(1337));
}
